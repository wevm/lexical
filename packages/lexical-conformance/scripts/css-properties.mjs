// Writes swift/Sources/Lexical/DOM/CSSProperties.swift from
// vectors/css/properties.json (`pnpm run css-properties`). ConformanceTests
// fails when the two disagree.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const {cases} = JSON.parse(
  readFileSync(
    root + 'packages/lexical-conformance/vectors/css/properties.json',
    'utf8',
  ),
);
const lines = cases.map(
  ({name, color, zeroLength, preserveCase, verbatim}) =>
    `  "${name}": ${(color ? 1 : 0) | (zeroLength ? 2 : 0) | (preserveCase ? 4 : 0) | (verbatim ? 8 : 0)},`,
);
writeFileSync(
  root + 'swift/Sources/Lexical/DOM/CSSProperties.swift',
  `// Generated by packages/lexical-conformance/scripts/css-properties.mjs from
// packages/lexical-conformance/vectors/css/properties.json. Do not edit.

/// The properties an inline style accepts, each with its
/// \`CSSPropertyTraits\` raw value.
package let cssPropertyTraitsByName: [String: UInt8] = [
${lines.join('\n')}
]
`,
);
