// Writes swift/Sources/Lexical/DOM/HTMLEntities.swift from
// vectors/html/entities.json (`pnpm run html-entities`). ConformanceTests
// fails when the two disagree.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const {cases} = JSON.parse(
  readFileSync(
    root + 'packages/lexical-conformance/vectors/html/entities.json',
    'utf8',
  ),
);
const escape = value =>
  [...value]
    .map(c => `\\u{${c.codePointAt(0).toString(16).toUpperCase()}}`)
    .join('');
const lines = cases.map(({name, value}) => `  "${name}": "${escape(value)}",`);
const legacy = cases.filter(c => c.legacy).map(c => `  "${c.name}",`);
writeFileSync(
  root + 'swift/Sources/Lexical/DOM/HTMLEntities.swift',
  `// Generated by packages/lexical-conformance/scripts/html-entities.mjs from
// packages/lexical-conformance/vectors/html/entities.json. Do not edit.

/// The named character references, without their \`&\` and \`;\`.
package let htmlNamedEntities: [String: String] = [
${lines.join('\n')}
]

/// The names that also decode without a semicolon.
package let htmlLegacyEntityNames: Set<String> = [
${legacy.join('\n')}
]
`,
);
