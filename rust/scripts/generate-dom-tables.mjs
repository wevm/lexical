// Generates the DOM's tables from the conformance vectors JS records, as
// packages/lexical-conformance/scripts/css-properties.mjs and
// html-entities.mjs do for the Swift port:
//
// - rust/lexical-editor/src/dom/css_properties.rs from
//   vectors/css/properties.json: the properties an inline style accepts
//   (jsdom's CSSStyleDeclaration) and how each normalizes values.
// - rust/lexical-editor/src/dom/html_entities.rs from
//   vectors/html/entities.json: the named character references and which of
//   them decode without a semicolon.
//
// The conformance runner fails when a table and its vectors disagree.
//
// Run from the repository root:
//   node rust/scripts/generate-dom-tables.mjs
import {readFileSync, writeFileSync} from 'node:fs';

const VECTORS = 'packages/lexical-conformance/vectors';
const OUT = 'rust/lexical-editor/src/dom';

const load = file =>
  JSON.parse(readFileSync(`${VECTORS}/${file}.json`, 'utf8')).cases;

/** Sorted as Rust compares `&str` (bytes), for a binary search. */
const byName = (a, b) =>
  Buffer.compare(Buffer.from(a.name), Buffer.from(b.name));

const properties = load('css/properties').sort(byName);
writeFileSync(
  `${OUT}/css_properties.rs`,
  `// Generated by rust/scripts/generate-dom-tables.mjs from
// packages/lexical-conformance/vectors/css/properties.json. Do not edit.

//! The properties an inline style declaration accepts, as jsdom's does,
//! each with its [\`CssPropertyTraits\`](super::css_values::CssPropertyTraits)
//! bits, sorted by name.

pub(crate) static CSS_PROPERTY_TRAITS: &[(&str, u8)] = &[
${properties
  .map(
    ({name, color, zeroLength, preserveCase, verbatim}) =>
      `    ("${name}", ${(color ? 1 : 0) | (zeroLength ? 2 : 0) | (preserveCase ? 4 : 0) | (verbatim ? 8 : 0)}),`,
  )
  .join('\n')}
];
`,
);

const escape = value =>
  [...value]
    .map(c => `\\u{${c.codePointAt(0).toString(16).toUpperCase()}}`)
    .join('');
const entities = load('html/entities').sort(byName);
writeFileSync(
  `${OUT}/html_entities.rs`,
  `// Generated by rust/scripts/generate-dom-tables.mjs from
// packages/lexical-conformance/vectors/html/entities.json. Do not edit.

//! The named character references of HTML, without their \`&\` and \`;\`,
//! sorted by name, and the names that also decode without a semicolon.

pub(crate) static HTML_NAMED_ENTITIES: &[(&str, &str)] = &[
${entities.map(({name, value}) => `    ("${name}", "${escape(value)}"),`).join('\n')}
];

pub(crate) static HTML_LEGACY_ENTITY_NAMES: &[&str] = &[
${entities
  .filter(c => c.legacy)
  .map(c => `    "${c.name}",`)
  .join('\n')}
];
`,
);
