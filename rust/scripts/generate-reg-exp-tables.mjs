// Generates rust/lexical-editor/src/markdown/reg_exp_tables.rs, the Unicode
// data of the markdown feature's JS regular expressions (`RegExp`), by
// asking the JS engine that records the vectors:
//
// - the code points `\p{P}`, `\p{S}`, `\p{L}`, `\p{N}` and `\p{Zs}` match
//   (with the `u` flag), so the port's tables are Node's Unicode version;
// - `Canonicalize` for the `i` flag without `u` (ECMA-262 22.2.2.7.3):
//   every BMP code unit whose `toUpperCase()` is one other code unit, unless
//   that maps a non-ASCII unit to ASCII.
//
// Run from the repository root with the Node in .nvmrc:
//   node rust/scripts/generate-reg-exp-tables.mjs
import {writeFileSync} from 'node:fs';

const OUT = 'rust/lexical-editor/src/markdown/reg_exp_tables.rs';

/** The ranges of code points `re` matches, as `[first, last]` pairs. */
function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const matches = cp < 0x110000 && re.test(String.fromCodePoint(cp));
    if (matches && start < 0) {
      start = cp;
    } else if (!matches && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
}

const hex = n => '0x' + n.toString(16).toUpperCase().padStart(4, '0');

function table(name, doc, re) {
  const rows = ranges(re)
    .map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`)
    .join('\n');
  return `/// ${doc}\npub(super) const ${name}: &[(u32, u32)] = &[\n${rows}\n];\n`;
}

const canonical = [];
for (let c = 0; c < 0x10000; c++) {
  if (c >= 0xd800 && c <= 0xdfff) {
    continue;
  }
  const upper = String.fromCharCode(c).toUpperCase();
  if (upper.length !== 1) {
    continue;
  }
  const u = upper.charCodeAt(0);
  if (u === c || (c >= 128 && u < 128)) {
    continue;
  }
  canonical.push(`    (${hex(c)}, ${hex(u)}),`);
}

const out = `//! @generated by \`rust/scripts/generate-reg-exp-tables.mjs\` from Node
//! ${process.version}'s regular expressions and \`toUpperCase\`. Do not edit
//! by hand; run the script again with the Node in \`.nvmrc\`.

${table('PUNCTUATION', '`\\p{P}`: General_Category Punctuation.', /\p{P}/u)}
${table('SYMBOL', '`\\p{S}`: General_Category Symbol.', /\p{S}/u)}
${table('LETTER', '`\\p{L}`: General_Category Letter.', /\p{L}/u)}
${table('NUMBER', '`\\p{N}`: General_Category Number.', /\p{N}/u)}
${table('SPACE_SEPARATOR', '`\\p{Zs}`: General_Category Space_Separator.', /\p{Zs}/u)}
/// \`Canonicalize\` without the \`u\` flag: each BMP code unit that the \`i\`
/// flag reads as another, with the one it reads as, sorted.
pub(super) const CANONICALIZE: &[(u16, u16)] = &[
${canonical.join('\n')}
];
`;

writeFileSync(OUT, out);
